"use client";

import { useEffect, useRef, useState } from "react";
import { AlertTriangle, LoaderCircle, RefreshCw } from "lucide-react";
import type { EmbeddingContext } from "amazon-quicksight-embedding-sdk";
import { isQuickEmbedUrl, platformQuickContentOptions, sessionDeadline,
  statusForQuickError, type QuickEmbedStatus } from "./quick-embedding";
import styles from "./quick.module.css";

// One hidden SDK control frame per browser document, not one per React render.
// Quick's public SDK has no destroy() API; each effect owns only its dashboard
// host and removes it on cleanup, including late asynchronous mounts.
let contextPromise: Promise<EmbeddingContext> | null = null;
function getContext() {
  if (!contextPromise) contextPromise = import("amazon-quicksight-embedding-sdk")
    .then(({ createEmbeddingContext }) => createEmbeddingContext())
    .catch((error) => { contextPromise = null; throw error; });
  return contextPromise;
}

export default function QuickDashboardEmbed({ embedUrl, issuedAt,
  sessionLifetimeMinutes, onRenew }: {
  embedUrl: string;
  issuedAt?: string;
  sessionLifetimeMinutes?: number;
  onRenew: () => void;
}) {
  const container = useRef<HTMLDivElement>(null);
  const [status, setStatus] = useState<QuickEmbedStatus>("loading");
  useEffect(() => {
    const root = container.current;
    if (!root) return;
    const host = document.createElement("div");
    host.className = styles.embedHost;
    root.replaceChildren(host);
    let active = true;
    let expiry: ReturnType<typeof setTimeout> | undefined;
    const fail = (next: QuickEmbedStatus) => {
      if (!active) return;
      active = false;
      clearTimeout(timeout);
      clearTimeout(expiry);
      host.remove();
      setStatus(next);
    };
    const timeout = setTimeout(() => fail("error"), 60_000);
    const deadline = sessionDeadline(issuedAt, sessionLifetimeMinutes);
    if (deadline !== null) expiry = setTimeout(
      () => fail("expired"), Math.max(0, deadline - Date.now())
    );
    void (async () => {
      try {
        if (!isQuickEmbedUrl(embedUrl)) { fail("error"); return; }
        const context = await getContext();
        if (!active) return;
        await context.embedDashboard({
          url: embedUrl, container: host, width: "100%", height: "820px",
          resizeHeightOnSizeChangedEvent: true, withIframePlaceholder: false,
          onChange: (event) => {
            if ("eventLevel" in event && event.eventLevel === "ERROR") fail("error");
          }
        }, {
          ...platformQuickContentOptions,
          onMessage: (event) => {
            if (!active) return;
            if (event.eventName === "CONTENT_LOADED") {
              clearTimeout(timeout);
              setStatus("ready");
              // Accessible name for the frame generated by the SDK.
              host.querySelector("iframe")?.setAttribute(
                "title", "Survey reports — Amazon Quick"
              );
            } else if (event.eventName === "ERROR_OCCURRED") {
              fail(statusForQuickError(event.message?.errorCode));
            }
          }
        });
        if (!active) host.remove();
      } catch {
        // Never log an embed URL, auth code, raw SDK event or respondent data.
        fail("error");
      }
    })();
    return () => {
      active = false;
      clearTimeout(timeout);
      clearTimeout(expiry);
      host.remove();
    };
  }, [embedUrl, issuedAt, sessionLifetimeMinutes]);

  return <div className={styles.embedShell} data-state={status}>
    <div ref={container} aria-busy={status === "loading"} />
    {status === "loading" && <div className={styles.embedStatus} role="status">
      <LoaderCircle size={25} className={styles.spin} />
      <strong>Loading survey reports</strong><span>Connecting to Amazon Quick…</span>
    </div>}
    {(status === "error" || status === "expired") && <div className={styles.embedStatus} role="alert">
      <AlertTriangle size={24} />
      <strong>{status === "expired" ? "Report session expired" : "Reports could not load"}</strong>
      <span>{status === "expired" ? "Open a fresh session to continue. Report filters will reset." :
        "This is a connection or report error, not a missing survey value."}</span>
      <button type="button" onClick={onRenew}><RefreshCw size={16} />Open fresh session</button>
    </div>}
  </div>;
}
